MOD_NAME="usbguard"
MOD_GROUP="security"
MOD_DESCRIPTION="USBGuard: only USB devices present at installation are allowed, new ones are blocked"
MOD_REQUIRES="system"

USBGUARD_RULES=/etc/usbguard/rules.conf

mod_check() {
	if os_in_container; then
		die "usbguard needs the kernel's USB authorisation; run it on a virtual machine or bare metal."
	fi
	return
}

mod_install() {
	pkg_install usbguard
	return
}

mod_configure() {
	# The policy is generated once from the devices connected now; later devices need an explicit rule
	# (usbguard allow-device ... -p), so a keyboard plugged in later cannot type commands.
	if [[ ! -s ${USBGUARD_RULES} ]] || ! grep -q 'lss' "${USBGUARD_RULES}"; then
		file_write 0600 root:root "${USBGUARD_RULES}" < <(
			printf '# Generated by lss (module usbguard) from the devices connected at installation.\n'
			usbguard generate-policy --no-hashes 2>/dev/null || true
		)
	fi
	local changed=${LSS_FILE_CHANGED:-0}
	svc_enable usbguard
	if [[ ${changed} == 1 ]]; then
		svc_restart usbguard
	fi
	return
}

mod_verify() {
	svc_is_active usbguard || die "usbguard: the service is not running."
	usbguard list-rules >/dev/null || die "usbguard: the daemon does not answer."
	return
}

mod_remove() {
	svc_disable usbguard
	file_remove "${USBGUARD_RULES}"
	if [[ ${LSS_PURGE:-0} == 1 ]]; then
		pkg_remove usbguard
	fi
	return
}
